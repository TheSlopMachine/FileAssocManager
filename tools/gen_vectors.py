#!/usr/bin/env python3
"""Regenerate tests/vectors.inc from tools/ref_hash.py (run from anywhere)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import ref_hash as r

def c_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

lines = ["/* Generated by tools/gen_vectors.py from tools/ref_hash.py - do not edit. */"]
n = 0
for kind, s in r.vectors():
    h = r.legacy_hash(r.ascii_lower(s)) if kind == "legacy" else r.latest_hash(s)
    lines.append('{ "%s", "%s", "%s" },' % (kind, c_escape(s), h))
    n += 1
# mixed-case input must give the same hash as its lower-case form (the C code lower-cases itself)
mixed = "COPYRIGHT (C) Microsoft. All Rights Reserved {3822B7CA-C2F4-4889-B8CC-4CE39A8FB81C}.PDD" \
        "01dcb06ea49f32a0B4DEB148-0249-44C4-A8D3-5409E822C599MSEdgePDFS-1-5-21-673349297-2269585490-1023937497-500"
lines.append('{ "latest", "%s", "%s" },' % (c_escape(mixed), r.latest_hash(mixed)))
lines.append('{ "legacy", "%s", "%s" },' % ("Mixed.CASE" + "x" * 30, r.legacy_hash(r.ascii_lower("Mixed.CASE" + "x" * 30))))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "vectors.inc"), "w").write("\n".join(lines) + "\n")
print("wrote", n + 2, "vectors")
